// جێبەجێکردنی وەرگێڕان لەسەر پەرەکان
function applyLanguage() {
    // ئەگەر پێشتر زمان دیاری نەکرابوو، با ئینگلیزی بێت بە بنەڕەت
    const currentLang = localStorage.getItem('selectedLang') || 'en';
    const data = translations[currentLang];

    // گۆڕینی ئاراستەی لاپەڕە (RTL/LTR)
    document.documentElement.dir = data.dir;
    document.documentElement.lang = currentLang;

    // گۆڕینی هەموو ئەو دەقانەی data-key یان هەیە
    document.querySelectorAll('[data-key]').forEach(element => {
        const key = element.getAttribute('data-key');
        if (data[key]) {
            element.innerText = data[key];
        }
    });

    // ڕەنگکردنی دوگمەی زمانی هەڵبژێردراو
    document.querySelectorAll('.lang-btn').forEach(btn => {
        btn.classList.remove('active');
        // پشکنین بەپێی دەقەکە یان پارامیتەرەکە
        if (btn.getAttribute('onclick').includes(`'${currentLang}'`)) {
            btn.classList.add('active');
        }
    });
}
function applyLanguage() {
    const currentLang = localStorage.getItem('selectedLang') || 'en';
    const data = translations[currentLang];

    // گۆڕینی ئاراستەی لاپەڕە
    document.documentElement.dir = data.dir;
    document.documentElement.lang = currentLang;

    // گۆڕینی هەموو ئەو توخمانەی data-key یان هەیە
    document.querySelectorAll('[data-key]').forEach(element => {
        const key = element.getAttribute('data-key');
        if (data[key]) {
            // پشکنین: ئەگەر توخمەکە وێنە بوو src بگۆڕە، ئەگەر نا innerText
            if (element.tagName === "IMG") {
                element.src = data[key];
            } else {
                element.innerText = data[key];
            }
        }
    });
}
// کاتی بارکردنی لاپەڕە، بانگی وەرگێڕان بکە
document.addEventListener('DOMContentLoaded', applyLanguage);
